import { z } from 'zod';
import { LIMITS } from './constants.js';
import { isEmail, normalizePhone } from './identifier.js';
import { normalizeEmail, normalizeUsername, validatePassword, validateUsername } from './validation.js';

/**
 * Auth request contracts, shared by the API (request validation) and the
 * mobile app (form validation) so both enforce identical rules.
 */

export const MIN_AGE = 13;
export const OTP_LENGTH = 6;

const PASSWORD_MESSAGES = {
  too_short: 'Use at least 10 characters.',
  too_long: 'Use at most 128 characters.',
  too_weak: 'Too simple — mix in more different characters.',
} as const;

const USERNAME_MESSAGES = {
  too_short: `At least ${LIMITS.usernameMin} characters.`,
  too_long: `At most ${LIMITS.usernameMax} characters.`,
  invalid_chars: 'Use letters, numbers, periods and underscores.',
  reserved: 'That username is reserved.',
} as const;

export const passwordSchema = z.string().superRefine((pw, ctx) => {
  const problem = validatePassword(pw);
  if (problem) ctx.addIssue({ code: 'custom', message: PASSWORD_MESSAGES[problem] });
});

export const usernameSchema = z
  .string()
  .transform(normalizeUsername)
  .superRefine((u, ctx) => {
    const problem = validateUsername(u);
    if (problem) ctx.addIssue({ code: 'custom', message: USERNAME_MESSAGES[problem] });
  });

export const emailSchema = z
  .string()
  .max(254)
  .refine(isEmail, 'Enter a valid email address.')
  .transform(normalizeEmail);

export const phoneSchema = z
  .string()
  .max(32)
  .transform((v, ctx) => {
    const e164 = normalizePhone(v);
    if (!e164) {
      ctx.addIssue({ code: 'custom', message: 'Enter a valid phone number with country code, e.g. +91 98765 43210.' });
      return z.NEVER;
    }
    return e164;
  });

export const otpCodeSchema = z.string().regex(new RegExp(`^\\d{${OTP_LENGTH}}$`), `Enter the ${OTP_LENGTH}-digit code.`);

/** Login identifier: email, phone (E.164) or username — classified server-side. */
export const identifierSchema = z.string().trim().min(3, 'Enter your email, phone or username.').max(254);

export function ageOn(dob: Date, now = new Date()): number {
  let age = now.getUTCFullYear() - dob.getUTCFullYear();
  const m = now.getUTCMonth() - dob.getUTCMonth();
  if (m < 0 || (m === 0 && now.getUTCDate() < dob.getUTCDate())) age--;
  return age;
}

export const dateOfBirthSchema = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/, 'Use YYYY-MM-DD.')
  .refine((s) => !Number.isNaN(Date.parse(`${s}T00:00:00Z`)), 'Enter a real date.')
  .refine((s) => {
    const age = ageOn(new Date(`${s}T00:00:00Z`));
    return age >= MIN_AGE && age <= 120;
  }, `You must be at least ${MIN_AGE} to use VYBORA.`);

export const signupSchema = z
  .object({
    email: emailSchema.optional(),
    phone: phoneSchema.optional(),
    password: passwordSchema,
    username: usernameSchema,
    displayName: z.string().trim().min(1, 'Enter your name.').max(LIMITS.displayNameMax),
    dateOfBirth: dateOfBirthSchema,
  })
  .strict()
  .refine((d) => !!d.email !== !!d.phone, { message: 'Sign up with either an email or a phone number.', path: ['email'] });

export const loginSchema = z.object({ identifier: identifierSchema, password: z.string().min(1, 'Enter your password.').max(128) }).strict();
export const otpRequestSchema = z.object({ identifier: identifierSchema }).strict();
export const otpLoginSchema = z.object({ identifier: identifierSchema, code: otpCodeSchema }).strict();
export const verifyCodeSchema = z.object({ code: otpCodeSchema }).strict();
export const forgotPasswordSchema = z.object({ identifier: identifierSchema }).strict();
export const resetPasswordSchema = z.object({ identifier: identifierSchema, code: otpCodeSchema, newPassword: passwordSchema }).strict();
export const refreshSchema = z.object({ refreshToken: z.string().min(20).max(200) }).strict();
export const changePasswordSchema = z
  .object({ currentPassword: z.string().min(1).max(128), newPassword: passwordSchema })
  .strict()
  .refine((d) => d.currentPassword !== d.newPassword, { message: 'Choose a different password.', path: ['newPassword'] });
export const deleteAccountSchema = z
  .object({ password: z.string().min(1).max(128).optional(), code: otpCodeSchema.optional() })
  .strict()
  .refine((d) => !!d.password || !!d.code, { message: 'Confirm with your password or a code.', path: ['password'] });
export const googleSignInSchema = z.object({ idToken: z.string().min(20).max(4096) }).strict();
export const appleSignInSchema = z
  .object({
    identityToken: z.string().min(20).max(4096),
    /** Raw nonce generated by the app; Apple embeds its SHA-256 in the token. */
    nonce: z.string().min(16).max(128),
    fullName: z.string().trim().max(LIMITS.displayNameMax).optional(),
  })
  .strict();

export type SignupInput = z.input<typeof signupSchema>;
export type LoginInput = z.input<typeof loginSchema>;

export const contactChannelSchema = z.enum(['email', 'phone']);
export const sendVerificationSchema = z.object({ channel: contactChannelSchema }).strict();
export const verifyContactSchema = z.object({ channel: contactChannelSchema, code: otpCodeSchema }).strict();
export const completeProfileSchema = z.object({ dateOfBirth: dateOfBirthSchema, username: usernameSchema.optional() }).strict();
